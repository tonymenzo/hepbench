#!/usr/bin/env python3
"""Build (and re-build) the llp_forward ground truth, reproducibly.

WHY THIS EXISTS
---------------
The original `truth.json` was generated by `soln/depr/derivation.py`, whose
flux default was

    FLUX_DEFAULT = "/tmp/parent_flux_allchan_2M.npz"

`/tmp` is purged by the OS. The 2M-event forward flux the graded reference was
built from is therefore gone, and `truth.json` has not been reproducible since.
That is not a bookkeeping detail: it means the reference could not be audited,
extended to new masses, or checked for self-consistency. This script fixes the
cause -- every artefact it produces lands under `soln/reference/`, is
checksummed, and is described by a manifest that records exactly how it was
made.

WHAT IT DOES
------------
  generate   one or more forward parent-flux samples (Pythia), archived with
             their seed, size and SHA-256 under reference/flux/
  truth      run the FULL pipeline (pseudoscalar + vector parents, both
             searches) over a flux sample -> reference/out/truth_<tag>.json
  sigma      compare two truth builds made from INDEPENDENT flux samples of
             the SAME size, which measures the reference's Monte-Carlo
             precision directly -- no sample-size deconvolution, and no
             cross-pipeline contamination

ON THE PREVIOUS sigma ESTIMATE
------------------------------
sigma_ref was previously estimated by comparing `truth.json` against
`fine_reach_contour.json`. Those are DIFFERENT PIPELINES, not two samples of
one: truth.json comes from derivation.py (8 parents, both searches) while
fine_reach_contour.json comes from code/leptonic_contour.py, which assembles
only the pseudoscalars (K, D, Ds) and calls
`PR.precompute(..., channel="mumu")` at both of its call sites. Their
disagreement is a physics difference, so it cannot calibrate a noise floor.
`sigma` below is the honest replacement.

USAGE
-----
    python build_reference.py generate --tag a --seed 1000 --n-soft 200000
    python build_reference.py generate --tag b --seed 2000 --n-soft 200000
    python build_reference.py truth    --tag a
    python build_reference.py truth    --tag b
    python build_reference.py sigma    --tags a b
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent          # soln/reference
SOLN = HERE.parent                              # soln
CODE = SOLN / "code"
FLUXDIR = HERE / "flux"
OUTDIR = HERE / "out"
MANIFEST = HERE / "manifest.json"

for d in (FLUXDIR, OUTDIR):
    d.mkdir(parents=True, exist_ok=True)


def sha256(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while (b := fh.read(chunk)):
            h.update(b)
    return h.hexdigest()


def load_manifest() -> dict:
    if MANIFEST.is_file():
        return json.loads(MANIFEST.read_text())
    return {"flux": {}, "truth": {}, "sigma": {}}


def save_manifest(m: dict) -> None:
    MANIFEST.write_text(json.dumps(m, indent=2, sort_keys=True))


def git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=str(SOLN)).decode().strip()
    except Exception:
        return "unknown"


# --------------------------------------------------------------------------
def cmd_generate(a) -> int:
    """Archive a forward parent-flux sample under reference/flux/."""
    out = FLUXDIR / f"parent_flux_{a.tag}.npz"
    if out.exists() and not a.force:
        print(f"{out.name} exists; pass --force to overwrite")
        return 1
    sys.path.insert(0, str(CODE))
    import generate_parent_flux as G

    t0 = time.time()
    # NOTE theta_max: reference.tex declares the forward harvest acceptance as
    # 0.05 rad, and the sandbox tells agents to use it. The generator's own
    # default is 1e-2. They must agree or the reference and the agents are
    # harvesting different parent populations -- so it is passed explicitly
    # here and recorded in the manifest.
    G.generate(a.n_soft, a.n_hard, a.pt_cut, a.seed, a.theta_max, str(out))
    dt = time.time() - t0

    m = load_manifest()
    m["flux"][a.tag] = dict(
        file=out.name, sha256=sha256(out), bytes=out.stat().st_size,
        n_soft=a.n_soft, n_hard=a.n_hard, pt_cut=a.pt_cut,
        theta_max=a.theta_max, seed=a.seed,
        generator="soln/code/generate_parent_flux.py",
        git_sha=git_sha(), wall_s=round(dt, 1),
        created_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    save_manifest(m)
    print(f"wrote {out}  ({out.stat().st_size/1e6:.1f} MB, {dt:.0f}s)")
    print(f"  sha256 {m['flux'][a.tag]['sha256'][:16]}...")
    return 0


def cmd_truth(a) -> int:
    """Run the FULL reference pipeline over an archived flux sample."""
    flux = FLUXDIR / f"parent_flux_{a.tag}.npz"
    if not flux.is_file():
        print(f"no such flux sample: {flux}", file=sys.stderr)
        return 2
    out = OUTDIR / f"truth_{a.tag}.json"

    # derivation.py writes soln/truth.json + soln/input.json UNCONDITIONALLY,
    # and those are the committed graded contract for two campaigns. Snapshot
    # them, let the generator run, collect its output under reference/out/, and
    # put the originals back. A rebuild must never mutate the live reference as
    # a side effect -- that is how the previous one became unauditable.
    #
    # The restore runs in a `finally`, and SIGTERM is converted to SystemExit so
    # that it does. A build takes tens of minutes; an earlier version restored
    # only on the success path, so a timeout or a Ctrl-C landing between
    # derivation's write and ours would have left the COMMITTED reference
    # overwritten by a partial rebuild, silently.
    guarded = [SOLN / "truth.json", SOLN / "input.json"]
    backup = {f: (f.read_bytes() if f.is_file() else None) for f in guarded}
    produced = SOLN / "truth.json"
    fresh = None
    fresh_input = None

    def _term(signum, frame):
        raise SystemExit(f"terminated by signal {signum}")

    prev = {s: signal.signal(s, _term)
            for s in (signal.SIGTERM, signal.SIGHUP)}
    env = dict(os.environ)
    t0 = time.time()
    try:
        # stdout is inherited, not captured: a build is long enough that live
        # progress matters, and capturing hid it until completion.
        proc = subprocess.run(
            [sys.executable, "-u", str(SOLN / "depr" / "derivation.py"),
             str(flux)], env=env)
        if proc.returncode == 0 and produced.is_file():
            fresh = produced.read_text()
            # input.json is the reference's provenance record (flux file, seed,
            # cap, geometry pins). Capture it too: promoting a truth.json
            # without its matching input.json is how the committed reference
            # came to describe a flux file that no longer exists.
            src = SOLN / "input.json"
            if src.is_file():
                fresh_input = src.read_text()
    finally:
        for f, b in backup.items():
            if b is None:
                f.unlink(missing_ok=True)
            else:
                f.write_bytes(b)
        for s, h in prev.items():
            signal.signal(s, h)
    dt = time.time() - t0

    if proc.returncode != 0:
        return proc.returncode
    if fresh is None:
        print("derivation.py produced no truth.json", file=sys.stderr)
        return 3
    out.write_text(fresh)
    if fresh_input is not None:
        (OUTDIR / f"input_{a.tag}.json").write_text(fresh_input)
    same = (backup[SOLN / "truth.json"] or b"") == (SOLN / "truth.json").read_bytes()
    print(f"  committed soln/truth.json restored unchanged: {same}")

    m = load_manifest()
    m["truth"][a.tag] = dict(
        file=out.name, sha256=sha256(out), from_flux=flux.name,
        flux_sha256=m["flux"].get(a.tag, {}).get("sha256"),
        generator="soln/depr/derivation.py", git_sha=git_sha(),
        wall_s=round(dt, 1),
        created_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    save_manifest(m)
    print(f"wrote {out}  ({dt:.0f}s)")
    return 0


def cmd_sigma(a) -> int:
    """sigma_ref from two independent SAME-SIZE builds -- the honest floor."""
    import math
    import statistics as st

    ta, tb = [json.loads((OUTDIR / f"truth_{t}.json").read_text()) for t in a.tags]
    pm = {t: {(r["search"], round(float(r["m"]), 4)): r
              for r in tr["_per_mass"]} for t, tr in zip(a.tags, (ta, tb))}
    ka, kb = pm[a.tags[0]], pm[a.tags[1]]

    rows, dpk, dlo, dhi = [], [], [], []
    for k in sorted(set(ka) & set(kb), key=lambda x: (x[0], x[1])):
        A, B = ka[k], kb[k]
        row = {"point": f"{k[0]}@{k[1]}"}
        if A.get("peak", 0) > 0 and B.get("peak", 0) > 0:
            d = abs(math.log10(B["peak"] / A["peak"])); dpk.append(d)
            row["peak_dex"] = round(d, 5)
        if A.get("band") and B.get("band"):
            d1 = abs(math.log10(B["band"][0] / A["band"][0]))
            d2 = abs(math.log10(B["band"][1] / A["band"][1]))
            dlo.append(d1); dhi.append(d2)
            row["g_lo_dex"] = round(d1, 5); row["g_hi_dex"] = round(d2, 5)
        rows.append(row)

    def summ(v):
        return dict(n=len(v), mean=round(st.mean(v), 5),
                    max=round(max(v), 5)) if v else None

    # two SAME-SIZE independent samples: the pair difference is sqrt(2)*sigma
    res = dict(tags=a.tags, points=rows,
               peak=summ(dpk), band_lo=summ(dlo), band_hi=summ(dhi),
               sigma_peak=round(st.mean(dpk) / math.sqrt(2), 5) if dpk else None,
               sigma_band=round(st.mean(dlo + dhi) / math.sqrt(2), 5) if dlo else None,
               note=("pair difference of two independent same-size builds is "
                     "sqrt(2)*sigma; no sample-size deconvolution needed"))
    m = load_manifest(); m["sigma"] = res; save_manifest(m)

    print(f"{'point':14s} {'peak dex':>9s} {'g_lo dex':>9s} {'g_hi dex':>9s}")
    for r in rows:
        print(f"  {r['point']:12s} {r.get('peak_dex', float('nan')):>9.4f} "
              f"{r.get('g_lo_dex', float('nan')):>9.4f} "
              f"{r.get('g_hi_dex', float('nan')):>9.4f}")
    print(f"\n  sigma_peak = {res['sigma_peak']}  dex")
    print(f"  sigma_band = {res['sigma_band']}  dex")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("generate", help="archive a forward parent-flux sample")
    g.add_argument("--tag", required=True)
    g.add_argument("--seed", type=int, required=True)
    g.add_argument("--n-soft", type=int, default=200000)
    g.add_argument("--n-hard", type=int, default=0)
    g.add_argument("--pt-cut", type=float, default=1.0)
    g.add_argument("--theta-max", type=float, default=0.05,
                   help="MUST match reference.tex (0.05 rad)")
    g.add_argument("--force", action="store_true")
    g.set_defaults(fn=cmd_generate)

    t = sub.add_parser("truth", help="full pipeline over an archived flux")
    t.add_argument("--tag", required=True)
    t.set_defaults(fn=cmd_truth)

    s = sub.add_parser("sigma", help="MC precision from two same-size builds")
    s.add_argument("--tags", nargs=2, required=True)
    s.set_defaults(fn=cmd_sigma)

    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    raise SystemExit(main())
